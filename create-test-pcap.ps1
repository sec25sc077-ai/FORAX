$packet = [byte[]](
    # Ethernet header: destination MAC, source MAC, IPv4 EtherType
    0x00,0x11,0x22,0x33,0x44,0x55,
    0x66,0x77,0x88,0x99,0xAA,0xBB,
    0x08,0x00,

    # IPv4 header
    0x45,0x00,0x00,0x28,
    0x12,0x34,0x40,0x00,
    0x40,0x06,0x00,0x00,
    0xC0,0xA8,0x01,0x0A,
    0x5D,0xB8,0xD8,0x22,

    # TCP header
    0x30,0x39,
    0x01,0xBB,
    0x00,0x00,0x00,0x01,
    0x00,0x00,0x00,0x00,
    0x50,0x02,0xFF,0xFF,
    0x00,0x00,0x00,0x00,

    # TCP payload
    0x46,0x4F,0x52,0x41,0x58
)

$globalHeader = [byte[]](
    0xD4,0xC3,0xB2,0xA1,
    0x02,0x00,0x04,0x00,
    0x00,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00,
    0xFF,0xFF,0x00,0x00,
    0x01,0x00,0x00,0x00
)

$timestamp = [byte[]](
    0x00,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00
)

$length = [BitConverter]::GetBytes([UInt32]$packet.Length)

if (-not [BitConverter]::IsLittleEndian) {
    [Array]::Reverse($length)
}

$record = [byte[]](
    $timestamp +
    $length +
    $length +
    $packet
)

[IO.File]::WriteAllBytes(
    "capture-real.pcap",
    [byte[]]($globalHeader + $record)
)

Write-Host "Created capture-real.pcap"
Write-Host "Packet length: $($packet.Length) bytes"
